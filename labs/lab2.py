def task_20():
    """20. Влияние пола на выбор тарифа (процентное соотношение) + визуализация."""
    if "Пол" not in df.columns:
        task_12()
    print("--- Задание 20: Влияние пола на выбор тарифа (проценты) ---")
    cross_tab = pd.crosstab(df["Тариф"], df["Пол"], normalize="columns") * 100
    print(cross_tab)

    cross_tab.plot(kind="bar", figsize=(8, 5))
    plt.title("Процентное соотношение выбора тарифов в зависимости от пола")
    plt.xlabel("Тариф")
    plt.ylabel("Процент (%)")
    plt.legend(title="Пол")
    plt.grid(axis="y")
    plt.show()


