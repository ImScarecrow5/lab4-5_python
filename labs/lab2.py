def task_23():
    """23. Переименование столбца, замена значений тарифов, удаление строк."""
    global df
    print("--- Задание 23: Манипуляции с датафреймом ---")

    if "Количество СМС" in df.columns:
        df = df.rename(columns={"Количество СМС": "Кол-во СМС"})
        print("После переименования 'Количество СМС' в 'Кол-во СМС':")
        print(df.columns.tolist())

    unique_tarifs = df["Тариф"].unique()
    mapping = {t: f"Т{i + 1}" for i, t in enumerate(unique_tarifs)}
    df["Тариф"] = df["Тариф"].map(mapping)
    print("\nПосле замены значений тарифов:")
    print(df[["Абонент", "Тариф"]].head())

    df = df[df["Абонент"] != "А2"]
    print("\nПосле удаления абонента А2:")
    print(df["Абонент"].values)

    df = df[~((df["Возраст"] >= 20) & (df["Возраст"] <= 30))]
    print("\nПосле удаления абонентов в возрасте от 20 до 30 лет:")
    print(df[["Абонент", "Возраст"]])


